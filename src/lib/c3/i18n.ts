const DICTIONARIES: Record<Language, C3Text> = { en, si, ta };

export function getC3Text(language: Language): C3Text {
  return DICTIONARIES[language] ?? en;
}

/** Replaces {name} placeholders. */
export function fmt(template: string, vars: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m));
}

/** Picks the taxonomy / role label for the current language. */
export function label(l: Localised, language: Language): string {
  return l[language] || l.en;
}
